"""Valkey key generation utilities."""
from __future__ import annotations

import hashlib

from butterscout.models.requests import SearchRequest


def generate_cache_key(request: SearchRequest) -> str:
    """Generate stable cache key from search request.

    Cache keys must be stable across requests with identical parameters.
    The key is generated by:
    1. Normalizing the query (lowercase, strip whitespace)
    2. Sorting domain lists for consistent ordering
    3. Combining all cache-relevant parameters
    4. Generating SHA256 hash for the final key

    Args:
        request: Search request to generate cache key for

    Returns:
        Cache key in format: bs:cache:<sha256-hash>
    """
    # Combine all cache-relevant params (domains sorted for stability)
    cache_parts = (
        f"{request.query.lower().strip()}"
        f":{request.max_results}"
        f":{request.include_content}"
        f":{sorted(request.options.domains)}"
        f":{sorted(request.options.exclude_domains)}"
        f":{request.options.freshness_days}"
        f":{request.options.language}"
    )

    # Generate SHA256 hash for key
    key_hash = hashlib.sha256(cache_parts.encode()).hexdigest()
    return f"bs:cache:{key_hash}"


def generate_rate_limit_key(identifier: str, key_type: str = "ip") -> str:
    """Generate rate limit key.

    Args:
        identifier: IP address or API key to generate rate limit key for
        key_type: Type of rate limit key - "ip" or "api_key"

    Returns:
        Rate limit key in format: bs:ratelimit:<type>:<hashed-identifier>
    """
    hashed = hashlib.sha256(identifier.encode()).hexdigest()[:16]
    return f"bs:ratelimit:{key_type}:{hashed}"


def generate_global_rate_limit_key(limit: int | None = None) -> str:
    """Generate global rate limit key.

    Args:
        limit: Optional limit value to namespace the global key.

    Returns:
        Global rate limit key: bs:ratelimit:global[:<limit>]
    """
    base_key = "bs:ratelimit:global"
    if limit is not None:
        return f"{base_key}:{limit}"
    return base_key
